/** Emits a renderer-independent settings model with KotlinPoet type and member specs. */
internal class SettingsStoreFileGenerator {
    private val item = ClassName(CORE_PACKAGE, "SettingsItem")
    private val value = ClassName(CORE_PACKAGE, "SettingsValue")
    private val abstractValue = ClassName(CORE_PACKAGE, "AbstractSettingsValue")
    private val number = ClassName(CORE_PACKAGE, "NumberType")
    private val resources = ClassName(CORE_PACKAGE, "SettingsResources")
    private val validation = ClassName(CORE_PACKAGE, "SettingsValidation")
    private val rangeInfo = ClassName(CORE_PACKAGE, "RangeBasedNumberInfo")
    private val resetMode = ClassName(CORE_PACKAGE, "SettingsResetMode")
    private val mutableStore = ClassName("top.ltfan.m3x.datastore", "MutableStore")

    fun generate(model: KSClassDeclaration): FileSpec {
        if (Modifier.DATA !in model.modifiers)
            processorError("@SettingsStore requires a data class")
        if (model.parentDeclaration != null)
            processorError("@SettingsStore must be a top-level data class")
        val modelType = model.toClassName()
        val resetModeName =
            model.annotation("SettingsStore")?.getAllArguments()?.get("resetMode").enumName()
                ?: "None"
        val defaultRoot =
            if (resetModeName == "Menu") {
                requireDefaultModelConstructor(model)
                modelType
            } else null
        val bindDataStore =
            model.annotation("SettingsStore")?.getAllArguments()?.get("bindDataStore") as? Boolean
                ?: true
        val describer =
            ClassName(CORE_PACKAGE, if (bindDataStore) "SettingsStoreDescriber" else "SettingsTree")
        val modelBinding =
            if (bindDataStore) mutableStore else ClassName(CORE_PACKAGE, "SettingsModel")
        val className =
            ClassName(model.packageName.asString(), model.simpleName.asString() + "Describer")
        val generated = mutableListOf<TypeSpec>()
        val roots = visit(model, emptyList(), model.simpleName.asString(), generated, defaultRoot)
        if (roots.isEmpty())
            processorError(
                "@SettingsStore ${modelType.canonicalName} has no @SettingsItem properties",
            )

        val rootList = constructors(roots)
        val storeType = modelBinding.parameterizedBy(modelType)
        val type =
            TypeSpec.classBuilder(className)
                .addKdoc("Generated by settings-page-processor.\n")
                .primaryConstructor(
                    FunSpec.constructorBuilder().addParameter("store", storeType).build(),
                )
                .addSuperinterface(describer)
                .addProperty(
                    PropertySpec.builder("store", storeType, KModifier.PRIVATE)
                        .initializer("store")
                        .build(),
                )
                .apply {
                    if (bindDataStore) {
                        addProperty(
                                PropertySpec.builder(
                                        "status",
                                        ClassName("kotlinx.coroutines.flow", "StateFlow")
                                            .parameterizedBy(
                                                ClassName(
                                                    CORE_PACKAGE,
                                                    "SettingsPersistenceStatus",
                                                ),
                                            ),
                                        KModifier.OVERRIDE,
                                    )
                                    .initializer(
                                        "store.status.%M()",
                                        MemberName(
                                            "top.ltfan.m3x.settingspage.datastore",
                                            "asSettingsStatus",
                                        ),
                                    )
                                    .build(),
                            )
                            .addFunction(
                                FunSpec.builder("retrySave")
                                    .addModifiers(KModifier.OVERRIDE)
                                    .addStatement("store.retrySave()")
                                    .build(),
                            )
                    }
                }
                .addProperty(
                    PropertySpec.builder("items", LIST.parameterizedBy(item), KModifier.OVERRIDE)
                        .initializer(rootList)
                        .build(),
                )
                .apply { generated.forEach(::addType) }
                .build()
        val factory =
            FunSpec.builder("settingsDescriber")
                .receiver(storeType)
                .returns(className)
                .addStatement("return %T(this)", className)
                .build()
        return FileSpec.builder(className.packageName, className.simpleName)
            .addType(type)
            .addFunction(factory)
            .build()
    }

    private fun visit(
        owner: KSClassDeclaration,
        parent: List<String>,
        prefix: String,
        generated: MutableList<TypeSpec>,
        defaultRoot: ClassName?,
    ): List<String> =
        owner.declarations
            .filterIsInstance<KSPropertyDeclaration>()
            .filter { it.annotation("SettingsItem") != null }
            .map { property ->
                val path = parent + property.simpleName.asString()
                requireEditableSettingsProperty(owner, property, path)
                val className = prefix + property.simpleName.asString().titlecaseFirst() + "Item"
                generated += itemSpec(owner, property, path, className, generated, defaultRoot)
                className
            }
            .toList()

    private fun itemSpec(
        owner: KSClassDeclaration,
        property: KSPropertyDeclaration,
        path: List<String>,
        className: String,
        generated: MutableList<TypeSpec>,
        defaultRoot: ClassName?,
    ): TypeSpec {
        val type = property.type.resolve()
        if (type.isMarkedNullable)
            processorError("Setting ${path.joinToString(".")} cannot be nullable")
        val args = property.annotation("SettingsItem")!!.getAllArguments()
        val category = args["type"].enumName() == "Category"
        val custom = property.annotation("CustomSettingsItem")
        if (category && custom != null)
            processorError("Category ${path.joinToString(".")} cannot be custom")
        val kind =
            when {
                category -> "Category"
                custom != null -> "Custom"
                type.qualifiedName() == "kotlin.Boolean" -> "Switch"
                type.qualifiedName() == "kotlin.String" -> "Text"
                type.isSupportedNumber() -> "SingleNumber"
                type.qualifiedName() == "kotlin.Pair" -> "NumberRange"
                type.qualifiedName() == "kotlin.collections.Set" -> "MultiSelector"
                type.declaration is KSClassDeclaration &&
                    (type.declaration as KSClassDeclaration).isChoice() -> "Selector"
                else ->
                    processorError("Unsupported setting type for ${path.joinToString(".")}: $type")
            }
        val element =
            when (kind) {
                "NumberRange" -> {
                    val parts = type.arguments.mapNotNull { it.type?.resolve() }
                    if (
                        parts.size != 2 ||
                            !parts[0].isSupportedNumber() ||
                            parts[0].qualifiedName() != parts[1].qualifiedName()
                    ) {
                        processorError(
                            "Number range ${path.joinToString(".")} needs two matching Int, Long, Float or Double values",
                        )
                    }
                    parts[0]
                }

                "MultiSelector" -> {
                    val choice =
                        type.arguments.singleOrNull()?.type?.resolve()
                            ?: processorError(
                                "Multi-selector ${path.joinToString(".")} needs an element type",
                            )
                    if ((choice.declaration as? KSClassDeclaration)?.isChoice() != true) {
                        processorError(
                            "Multi-selector ${path.joinToString(".")} needs enum or sealed choices",
                        )
                    }
                    choice
                }

                else -> type
            }
        if (
            kind !in setOf("SingleNumber", "NumberRange") &&
                property.finiteAnnotations().isNotEmpty()
        ) {
            processorError("Finite bounds require a numeric setting: ${path.joinToString(".")}")
        }
        if (kind != "Text" && property.annotation("TextInput") != null) {
            processorError("@TextInput requires a String setting: ${path.joinToString(".")}")
        }
        if (
            kind == "Category" &&
                Modifier.DATA !in (type.declaration as? KSClassDeclaration)?.modifiers.orEmpty()
        ) {
            processorError("Category ${path.joinToString(".")} must be a data class")
        }
        val resource = resourceExpression(property, args, element, kind)
        val dependencies =
            (args["dependsOn"] as? List<*>)
                ?.mapNotNull {
                    (it as? KSValueArgument)?.value as? String ?: it as? String
                }
                .orEmpty()
        val parentPath = path.dropLast(1)
        dependencies.forEach { name ->
            val sibling =
                owner.declarations.filterIsInstance<KSPropertyDeclaration>().firstOrNull {
                    it.simpleName.asString() == name
                }
            if (sibling?.type?.resolve()?.qualifiedName() != "kotlin.Boolean") {
                processorError(
                    "Dependency '$name' of ${path.joinToString(".")} must name a sibling Boolean property",
                )
            }
        }
        val dependencyExpr =
            dependencies.joinToString(" && ") { read(parentPath + it) }.ifEmpty { "true" }
        val showExpr =
            if (args["dependencyType"].enumName() == "ShowHide") dependencyExpr else "true"
        val enabledExpr =
            if (args["dependencyType"].enumName() == "ShowHide") "true" else dependencyExpr
        val valueType = type.toTypeName()
        val elementType = element.toTypeName()
        val interfaceType =
            when (kind) {
                "Category" -> item.nestedClass("Category")
                "Switch",
                "Text" -> item.nestedClass("Item").nestedClass(kind)
                else ->
                    item
                        .nestedClass("Item")
                        .nestedClass(kind)
                        .parameterizedBy(if (kind == "Custom") valueType else elementType)
            }
        val children =
            if (kind == "Category") {
                val nested =
                    visit(
                        type.declaration as KSClassDeclaration,
                        path,
                        className,
                        generated,
                        defaultRoot,
                    )
                if (nested.isEmpty())
                    processorError("Category ${path.joinToString(".")} has no settings")
                constructors(nested)
            } else CodeBlock.of("null")

        val builder =
            TypeSpec.classBuilder(className)
                .addModifiers(KModifier.PUBLIC, KModifier.INNER)
                .addSuperinterface(interfaceType)
                .addProperty(
                    PropertySpec.builder("id", STRING, KModifier.OVERRIDE)
                        .initializer("%S", path.joinToString("."))
                        .build(),
                )
                .addProperty(
                    PropertySpec.builder("resources", resources, KModifier.OVERRIDE)
                        .initializer(resource)
                        .build(),
                )
        if (kind !in setOf("Selector", "MultiSelector")) {
            builder.addProperty(
                PropertySpec.builder(
                        "children",
                        LIST.parameterizedBy(item).copy(nullable = kind != "Category"),
                        KModifier.OVERRIDE,
                    )
                    .initializer(children)
                    .build(),
            )
        }
        builder
            .addProperty(dynamicProperty("shouldShow", BOOLEAN, showExpr))
            .addProperty(dynamicProperty("enabled", BOOLEAN, enabledExpr))
        if (defaultRoot != null && kind != "Category") {
            builder
                .addProperty(
                    PropertySpec.builder("resetMode", resetMode, KModifier.OVERRIDE)
                        .initializer("%T.Menu", resetMode)
                        .build(),
                )
                .addProperty(
                    PropertySpec.builder(
                            "defaultValue",
                            defaultValuePropertyType(kind, valueType, elementType),
                            KModifier.OVERRIDE,
                        )
                        .getter(
                            FunSpec.getterBuilder()
                                .addStatement(
                                    "return %L",
                                    defaultValueExpression(kind, defaultRoot, path),
                                )
                                .build(),
                        )
                        .build(),
                )
        }
        when (kind) {
            "Category" -> Unit
            "Selector",
            "MultiSelector" ->
                choiceMembers(
                    builder,
                    element.declaration as KSClassDeclaration,
                    path,
                    kind,
                    defaultRoot,
                )
            else ->
                builder.addProperty(
                    valueProperty(
                        valueType,
                        readCode(path),
                        copyCode(path, CodeBlock.of("newValue")),
                    ),
                )
        }
        when (kind) {
            "SingleNumber" -> {
                if (property.finiteAnnotations().size > 1)
                    processorError(
                        "Single number ${path.joinToString(".")} needs at most one finite annotation",
                    )
                builder.addProperty(
                    PropertySpec.builder(
                            "type",
                            number.parameterizedBy(elementType),
                            KModifier.OVERRIDE,
                        )
                        .initializer(numberConfig(property, 0, element))
                        .build(),
                )
                builder.addFunction(validateFunction(elementType, "number", "candidate, type"))
            }

            "NumberRange" -> {
                val count = property.finiteAnnotations().size
                if (count != 0 && count != 2)
                    processorError(
                        "Range ${path.joinToString(".")} needs zero or two finite annotations",
                    )
                builder.addProperty(
                    PropertySpec.builder(
                            "startType",
                            number.parameterizedBy(elementType),
                            KModifier.OVERRIDE,
                        )
                        .initializer(numberConfig(property, 0, element))
                        .build(),
                )
                builder.addProperty(
                    PropertySpec.builder(
                            "endType",
                            number.parameterizedBy(elementType),
                            KModifier.OVERRIDE,
                        )
                        .initializer(numberConfig(property, 1, element))
                        .build(),
                )
                builder.addFunction(
                    validateFunction(valueType, "range", "candidate, startType, endType"),
                )
            }

            "Text" -> addTextMembers(builder, property, path)
            "Custom" -> {
                val rendererId = custom!!.getAllArguments()["rendererId"] as? String
                if (rendererId.isNullOrBlank())
                    processorError("Custom item ${path.joinToString(".")} needs a rendererId")
                builder.addProperty(
                    PropertySpec.builder("rendererId", STRING, KModifier.OVERRIDE)
                        .initializer("%S", rendererId)
                        .build(),
                )
            }
        }
        return builder.build()
    }

    private fun choiceMembers(
        builder: TypeSpec.Builder,
        choice: KSClassDeclaration,
        path: List<String>,
        kind: String,
        defaultRoot: ClassName?,
    ) {
        val choiceType = choice.toClassName()
        val choices =
            when (choice.classKind) {
                ClassKind.ENUM_CLASS ->
                    choice.declarations
                        .filterIsInstance<KSClassDeclaration>()
                        .filter { it.classKind == ClassKind.ENUM_ENTRY }
                        .toList()

                else -> choice.getSealedSubclasses().toList()
            }
        if (choices.isEmpty()) processorError("Choice ${choiceType.canonicalName} has no options")
        val multiple = kind == "MultiSelector"
        val wrapped = value.parameterizedBy(choiceType)
        val candidateType = if (multiple) SET.parameterizedBy(wrapped) else wrapped
        val getter =
            if (multiple) CodeBlock.of("%L.map { describeValue(it) }.toSet()", readCode(path))
            else CodeBlock.of("describeValue(%L)", readCode(path))
        val newValue =
            CodeBlock.of(if (multiple) "newValue.map { it.value }.toSet()" else "newValue.value")
        builder.addProperty(valueProperty(candidateType, getter, copyCode(path, newValue)))
        val childrenType = LIST.parameterizedBy(item).copy(nullable = !multiple)
        builder.addProperty(
            PropertySpec.builder("children", childrenType, KModifier.OVERRIDE)
                .getter(
                    FunSpec.getterBuilder()
                        .addStatement(
                            "return %L",
                            if (multiple) "value.flatMap { it.children.orEmpty() }"
                            else "value.children",
                        )
                        .build(),
                )
                .build(),
        )
        val optionCode = CodeBlock.builder().add("listOf(\n").indent()
        choices.forEachIndexed { index, option ->
            optionCode.add(
                "%N(%L)",
                option.simpleName.asString().titlecaseFirst() + "Value",
                optionExpression(choice, option),
            )
            optionCode.add(if (index == choices.lastIndex) "\n" else ",\n")
        }
        optionCode.unindent().add(")")
        builder.addProperty(
            PropertySpec.builder("options", LIST.parameterizedBy(wrapped), KModifier.OVERRIDE)
                .initializer(optionCode.build())
                .build(),
        )
        val describe =
            FunSpec.builder("describeValue")
                .addModifiers(KModifier.PRIVATE)
                .addParameter("raw", choiceType)
                .returns(wrapped)
                .beginControlFlow("return when (raw)")
        choices.forEach { option ->
            val condition =
                if (choice.classKind == ClassKind.ENUM_CLASS) optionExpression(choice, option)
                else CodeBlock.of("is %T", option.toClassName())
            describe.addStatement(
                "%L -> %N(raw)",
                condition,
                option.simpleName.asString().titlecaseFirst() + "Value",
            )
        }
        builder.addFunction(describe.endControlFlow().build())
        choices.forEach { option ->
            builder.addType(optionWrapper(choice, option, path, multiple, defaultRoot))
        }
    }

    private fun optionWrapper(
        choice: KSClassDeclaration,
        option: KSClassDeclaration,
        path: List<String>,
        multiple: Boolean,
        defaultRoot: ClassName?,
    ): TypeSpec {
        val choiceType = choice.toClassName()
        val wrapper = option.simpleName.asString().titlecaseFirst() + "Value"
        val fields =
            option.declarations
                .filterIsInstance<KSPropertyDeclaration>()
                .filter { it.annotation("SettingsItem") != null }
                .toList()
        if (fields.isNotEmpty() && Modifier.DATA !in option.modifiers) {
            processorError(
                "Option ${option.simpleName.asString()} with settings must be a data class",
            )
        }
        val builder =
            TypeSpec.classBuilder(wrapper)
                .addModifiers(KModifier.PRIVATE, KModifier.INNER)
                .primaryConstructor(
                    FunSpec.constructorBuilder().addParameter("value", choiceType).build(),
                )
                .superclass(abstractValue.parameterizedBy(choiceType))
                .addProperty(
                    PropertySpec.builder("value", choiceType, KModifier.OVERRIDE)
                        .initializer("value")
                        .build(),
                )
                .addProperty(
                    PropertySpec.builder("id", STRING, KModifier.OVERRIDE)
                        .initializer(
                            "%S",
                            path.joinToString(".") + "." + option.simpleName.asString(),
                        )
                        .build(),
                )
                .addProperty(
                    PropertySpec.builder("resources", resources, KModifier.OVERRIDE)
                        .initializer(optionResource(choice, option))
                        .build(),
                )
        if (fields.isNotEmpty()) {
            builder.addProperty(
                PropertySpec.builder("children", LIST.parameterizedBy(item), KModifier.OVERRIDE)
                    .initializer(
                        constructors(
                            fields.map { it.simpleName.asString().titlecaseFirst() + "Item" },
                        ),
                    )
                    .build(),
            )
            fields.forEach {
                builder.addType(optionFieldSpec(it, path, option, multiple, defaultRoot))
            }
        }
        return builder.build()
    }

    private fun optionFieldSpec(
        property: KSPropertyDeclaration,
        parentPath: List<String>,
        option: KSClassDeclaration,
        multiple: Boolean,
        defaultRoot: ClassName?,
    ): TypeSpec {
        val optionType = option.toClassName()
        val field = property.simpleName.asString()
        val idPath = buildList {
            addAll(parentPath)
            add(option.simpleName.asString())
            add(field)
        }
        requireEditableSettingsProperty(option, property, idPath)
        val type = property.type.resolve()
        if (type.isMarkedNullable)
            processorError("Option setting ${idPath.joinToString(".")} cannot be nullable")
        if (
            (property.annotation("SettingsItem")!!.getAllArguments()["dependsOn"] as? List<*>)
                ?.isNotEmpty() == true
        ) {
            processorError(
                "Option setting dependencies are not supported: ${idPath.joinToString(".")}",
            )
        }
        val custom = property.annotation("CustomSettingsItem")
        val kind =
            when {
                custom != null -> "Custom"
                type.qualifiedName() == "kotlin.Boolean" -> "Switch"
                type.qualifiedName() == "kotlin.String" -> "Text"
                type.isSupportedNumber() -> "SingleNumber"
                else ->
                    processorError("Unsupported option setting type: ${idPath.joinToString(".")}")
            }
        val valueType = type.toTypeName()
        val interfaceType =
            item.nestedClass("Item").nestedClass(kind).let {
                if (kind == "Custom" || kind == "SingleNumber") it.parameterizedBy(valueType)
                else it
            }
        val selected =
            if (multiple)
                CodeBlock.of(
                    "%L.filterIsInstance<%T>().firstOrNull()",
                    read(parentPath),
                    optionType,
                )
            else CodeBlock.of("(%L as? %T)", read(parentPath), optionType)
        val rawCurrent = read(parentPath, "current")
        val updated =
            if (multiple)
                CodeBlock.of(
                    "%L.map { if (it is %T) it.copy(%N = newValue) else it }.toSet()",
                    rawCurrent,
                    optionType,
                    field,
                )
            else
                CodeBlock.of(
                    "if (%L is %T) %L.copy(%N = newValue) else %L",
                    rawCurrent,
                    optionType,
                    rawCurrent,
                    field,
                    rawCurrent,
                )
        val visible =
            if (multiple) CodeBlock.of("%L.any { it is %T }", read(parentPath), optionType)
            else CodeBlock.of("%L is %T", read(parentPath), optionType)
        val builder =
            TypeSpec.classBuilder(field.titlecaseFirst() + "Item")
                .addModifiers(KModifier.PRIVATE, KModifier.INNER)
                .addSuperinterface(interfaceType)
                .addProperty(
                    PropertySpec.builder("id", STRING, KModifier.OVERRIDE)
                        .initializer("%S", idPath.joinToString("."))
                        .build(),
                )
                .addProperty(
                    PropertySpec.builder("resources", resources, KModifier.OVERRIDE)
                        .initializer(
                            resourceExpression(
                                property,
                                property.annotation("SettingsItem")!!.getAllArguments(),
                                type,
                                kind,
                            ),
                        )
                        .build(),
                )
                .addProperty(
                    PropertySpec.builder(
                            "children",
                            LIST.parameterizedBy(item).copy(nullable = true),
                            KModifier.OVERRIDE,
                        )
                        .initializer("null")
                        .build(),
                )
                .addProperty(dynamicProperty("shouldShow", BOOLEAN, visible))
                .addProperty(dynamicProperty("enabled", BOOLEAN, "true"))
                .addProperty(
                    valueProperty(
                        valueType,
                        CodeBlock.of("(%L ?: %T()).%N", selected, optionType, field),
                        copyCode(parentPath, updated),
                    ),
                )
        if (defaultRoot != null) {
            val freshModel = CodeBlock.of("%T()", defaultRoot)
            val defaultRaw = readCode(parentPath, freshModel)
            val defaultSelected =
                if (multiple)
                    CodeBlock.of(
                        "%L.filterIsInstance<%T>().firstOrNull()",
                        defaultRaw,
                        optionType,
                    )
                else CodeBlock.of("(%L as? %T)", defaultRaw, optionType)
            builder
                .addProperty(
                    PropertySpec.builder("resetMode", resetMode, KModifier.OVERRIDE)
                        .initializer("%T.Menu", resetMode)
                        .build(),
                )
                .addProperty(
                    PropertySpec.builder(
                            "defaultValue",
                            valueType.copy(nullable = true),
                            KModifier.OVERRIDE,
                        )
                        .getter(
                            FunSpec.getterBuilder()
                                .addStatement(
                                    "return (%L ?: %T()).%N",
                                    defaultSelected,
                                    optionType,
                                    field,
                                )
                                .build(),
                        )
                        .build(),
                )
        }
        when (kind) {
            "Text" -> addTextMembers(builder, property, idPath)
            "SingleNumber" -> {
                if (property.finiteAnnotations().size > 1)
                    processorError(
                        "Option number needs at most one finite annotation: ${
                        idPath.joinToString(
                            ".",
                        )
                    }",
                    )
                builder.addProperty(
                    PropertySpec.builder(
                            "type",
                            number.parameterizedBy(valueType),
                            KModifier.OVERRIDE,
                        )
                        .initializer(numberConfig(property, 0, type))
                        .build(),
                )
                builder.addFunction(validateFunction(valueType, "number", "candidate, type"))
            }

            "Custom" -> {
                val rendererId = custom!!.getAllArguments()["rendererId"] as? String
                if (rendererId.isNullOrBlank())
                    processorError(
                        "Custom option setting needs a rendererId: ${
                        idPath.joinToString(
                            ".",
                        )
                    }",
                    )
                builder.addProperty(
                    PropertySpec.builder("rendererId", STRING, KModifier.OVERRIDE)
                        .initializer("%S", rendererId)
                        .build(),
                )
            }
        }
        return builder.build()
    }

    private fun addTextMembers(
        builder: TypeSpec.Builder,
        property: KSPropertyDeclaration,
        path: List<String>,
    ) {
        val args = property.annotation("TextInput")?.getAllArguments().orEmpty()
        val min = (args["minLength"] as? Int) ?: 0
        val max = (args["maxLength"] as? Int) ?: Int.MAX_VALUE
        if (min !in 0..max)
            processorError("Invalid text length limits on ${path.joinToString(".")}")
        builder
            .addProperty(
                PropertySpec.builder("minLength", INT, KModifier.OVERRIDE)
                    .initializer("%L", min)
                    .build(),
            )
            .addProperty(
                PropertySpec.builder("maxLength", INT, KModifier.OVERRIDE)
                    .initializer("%L", max)
                    .build(),
            )
            .addProperty(
                PropertySpec.builder("multiline", BOOLEAN, KModifier.OVERRIDE)
                    .initializer("%L", (args["multiline"] as? Boolean) ?: false)
                    .build(),
            )
            .addFunction(validateFunction(STRING, "text", "candidate, minLength, maxLength"))
    }

    private fun validateFunction(
        candidateType: TypeName,
        method: String,
        arguments: String,
    ): FunSpec =
        FunSpec.builder("validate")
            .addModifiers(KModifier.OVERRIDE)
            .addParameter("candidate", candidateType)
            .returns(STRING.copy(nullable = true))
            .addStatement("return %T.%N(%L)", validation, method, arguments)
            .build()

    private fun valueProperty(type: TypeName, getter: CodeBlock, updated: CodeBlock): PropertySpec =
        PropertySpec.builder("value", type, KModifier.OVERRIDE)
            .mutable(true)
            .getter(FunSpec.getterBuilder().addStatement("return %L", getter).build())
            .setter(
                FunSpec.setterBuilder()
                    .addParameter("newValue", type)
                    .addStatement("store.update { current -> %L }", updated)
                    .build(),
            )
            .build()

    private fun defaultValuePropertyType(
        kind: String,
        valueType: TypeName,
        elementType: TypeName,
    ): TypeName =
        when (kind) {
            "Selector" -> value.parameterizedBy(elementType).copy(nullable = true)
            "MultiSelector" ->
                SET.parameterizedBy(value.parameterizedBy(elementType)).copy(nullable = true)
            else -> valueType.copy(nullable = true)
        }

    private fun defaultValueExpression(
        kind: String,
        defaultRoot: ClassName,
        path: List<String>,
    ): CodeBlock {
        val freshModel = CodeBlock.of("%T()", defaultRoot)
        val rawDefault = readCode(path, freshModel)
        return when (kind) {
            "Selector" -> CodeBlock.of("describeValue(%L)", rawDefault)
            "MultiSelector" -> CodeBlock.of("%L.map { describeValue(it) }.toSet()", rawDefault)
            else -> rawDefault
        }
    }

    private fun requireDefaultModelConstructor(model: KSClassDeclaration) {
        val constructor = model.primaryConstructor
        if (
            constructor == null ||
                constructor.parameters.any { !it.hasDefault } ||
                Modifier.PRIVATE in constructor.modifiers ||
                Modifier.PROTECTED in constructor.modifiers ||
                Modifier.PRIVATE in model.modifiers ||
                Modifier.PROTECTED in model.modifiers
        ) {
            processorError(
                "@SettingsStore(resetMode = Menu) requires an accessible no-argument default constructor",
            )
        }
    }

    private fun dynamicProperty(name: String, type: TypeName, expression: String): PropertySpec =
        dynamicProperty(name, type, CodeBlock.of("%L", expression))

    private fun dynamicProperty(name: String, type: TypeName, expression: CodeBlock): PropertySpec =
        PropertySpec.builder(name, type, KModifier.OVERRIDE)
            .getter(FunSpec.getterBuilder().addStatement("return %L", expression).build())
            .build()

    private fun constructors(names: List<String>): CodeBlock =
        CodeBlock.builder()
            .add("listOf(")
            .apply {
                names.forEachIndexed { index, name ->
                    add(if (index == 0) "%N()" else ", %N()", name)
                }
            }
            .add(")")
            .build()

    private fun optionExpression(owner: KSClassDeclaration, option: KSClassDeclaration): CodeBlock {
        if (owner.classKind == ClassKind.ENUM_CLASS)
            return CodeBlock.of(
                "%T.%N",
                owner.toClassName(),
                option.simpleName.asString(),
            )
        val type = option.toClassName()
        return when (option.classKind) {
            ClassKind.OBJECT -> CodeBlock.of("%T", type)
            ClassKind.CLASS -> {
                if (
                    Modifier.DATA !in option.modifiers ||
                        option.primaryConstructor?.parameters?.any { !it.hasDefault } == true
                ) {
                    processorError(
                        "Sealed option ${type.canonicalName} must be an object or data class with default constructor values",
                    )
                }
                CodeBlock.of("%T()", type)
            }

            else -> processorError("Unsupported sealed option ${type.canonicalName}")
        }
    }

    private fun optionResource(owner: KSClassDeclaration, option: KSClassDeclaration): CodeBlock {
        val specified =
            option.annotations
                .firstOrNull { it.shortName.asString() == "SettingsValue" }
                ?.getAllArguments()
                ?.get("resourceClass") as? KSType
        if (specified != null && specified.qualifiedName() != "kotlin.Unit") {
            val declaration =
                specified.declaration as? KSClassDeclaration
                    ?: processorError(
                        "Invalid resource class for option ${option.simpleName.asString()}",
                    )
            if (!declaration.providesResources())
                processorError(
                    "Option resource ${declaration.qualifiedName!!.asString()} must provide SettingsResources",
                )
            return CodeBlock.of("%T", declaration.toClassName())
        }
        if (owner.classKind == ClassKind.ENUM_CLASS) {
            if (!owner.implementsResources())
                processorError(
                    "Enum ${owner.qualifiedName!!.asString()} must implement SettingsResources",
                )
            return optionExpression(owner, option)
        }
        if (!option.providesResources())
            processorError(
                "Sealed option ${option.qualifiedName!!.asString()} must provide SettingsResources",
            )
        return CodeBlock.of("%T", option.toClassName())
    }

    private fun resourceExpression(
        property: KSPropertyDeclaration,
        args: Map<String, Any?>,
        valueType: KSType,
        kind: String,
    ): CodeBlock {
        val specified = args["resourceObject"] as? KSType
        if (specified != null && specified.qualifiedName() != "kotlin.Unit") {
            val declaration =
                specified.declaration as? KSClassDeclaration
                    ?: processorError(
                        "Invalid resource object on ${property.simpleName.asString()}",
                    )
            if (!declaration.providesResources())
                processorError(
                    "Resource ${declaration.qualifiedName!!.asString()} must provide SettingsResources",
                )
            return CodeBlock.of("%T", declaration.toClassName())
        }
        val declaration = valueType.declaration as? KSClassDeclaration
        if (
            kind in setOf("Selector", "MultiSelector") &&
                declaration != null &&
                (declaration.classKind == ClassKind.OBJECT || declaration.hasCompanionObject())
        ) {
            if (!declaration.providesResources())
                processorError(
                    "Choice ${declaration.qualifiedName!!.asString()} must provide SettingsResources",
                )
            return CodeBlock.of("%T", declaration.toClassName())
        }
        processorError(
            "Settings item '${property.simpleName.asString()}' must declare a resource object",
        )
    }

    private fun numberConfig(
        property: KSPropertyDeclaration,
        index: Int,
        valueType: KSType,
    ): CodeBlock {
        val valueKind =
            valueType.qualifiedName()?.substringAfterLast('.')
                ?: processorError("Unsupported numeric type on ${property.simpleName.asString()}")
        if (valueKind !in setOf("Int", "Long", "Float", "Double")) {
            processorError("Unsupported numeric type on ${property.simpleName.asString()}")
        }
        val finite =
            property.finiteAnnotations().getOrNull(index)
                ?: return CodeBlock.of("%T.input%N()", number, valueKind)
        val args = finite.getAllArguments()
        if (finite.shortName.asString() == "FiniteNumber") {
            val descriptor =
                args["describer"] as? KSType
                    ?: processorError(
                        "FiniteNumber requires a describer on ${property.simpleName.asString()}",
                    )
            val declaration =
                descriptor.declaration as? KSClassDeclaration
                    ?: processorError(
                        "Invalid finite describer on ${property.simpleName.asString()}",
                    )
            if (declaration.classKind != ClassKind.OBJECT && !declaration.hasCompanionObject()) {
                processorError(
                    "Finite describer must be an object or companion object: ${declaration.qualifiedName!!.asString()}",
                )
            }
            val name = declaration.toClassName()
            return CodeBlock.of(
                "%T.finite%N(%T.type, %T.min, %T.max, %T.step, %T.allowInput, %T.sliderMode)",
                number,
                valueKind,
                name,
                name,
                name,
                name,
                name,
                name,
            )
        }
        val expected =
            when (finite.shortName.asString()) {
                "FiniteInt" -> "kotlin.Int"
                "FiniteLong" -> "kotlin.Long"
                "FiniteFloat" -> "kotlin.Float"
                "FiniteDouble" -> "kotlin.Double"
                else -> processorError("Unsupported finite annotation")
            }
        if (valueType.qualifiedName() != expected)
            processorError("Finite bounds type does not match ${property.simpleName.asString()}")
        val type = args["type"].enumName() ?: processorError("Finite number needs an input type")
        val min = args["min"] as? Number ?: processorError("Finite number needs min")
        val max = args["max"] as? Number ?: processorError("Finite number needs max")
        val step = args["step"] as? Number ?: processorError("Finite number needs step")
        if (!validFiniteBounds(min, max, step, NumberKind.valueOf(valueKind))) {
            processorError("Invalid finite bounds on ${property.simpleName.asString()}")
        }
        val suffix =
            when (finite.shortName.asString()) {
                "FiniteFloat" -> "f"
                "FiniteLong" -> "L"
                else -> ""
            }
        val allow = (args["allowInput"] as? Boolean) ?: true
        val sliderMode = args["sliderMode"].enumName() ?: "Continuous"
        if (sliderMode == "Steps") {
            if (type != "Slider")
                processorError(
                    "sliderMode=Steps requires a Slider on ${property.simpleName.asString()}",
                )
            try {
                val bounds =
                    when (valueKind) {
                        "Int" ->
                            NumberType.finiteInt(
                                RangeBasedNumberInfo.Type.Slider,
                                min.toInt(),
                                max.toInt(),
                                step.toInt(),
                                allow,
                                SliderMode.Steps,
                            )

                        "Long" ->
                            NumberType.finiteLong(
                                RangeBasedNumberInfo.Type.Slider,
                                min.toLong(),
                                max.toLong(),
                                step.toLong(),
                                allow,
                                SliderMode.Steps,
                            )

                        "Float" ->
                            NumberType.finiteFloat(
                                RangeBasedNumberInfo.Type.Slider,
                                min.toFloat(),
                                max.toFloat(),
                                step.toFloat(),
                                allow,
                                SliderMode.Steps,
                            )

                        else ->
                            NumberType.finiteDouble(
                                RangeBasedNumberInfo.Type.Slider,
                                min.toDouble(),
                                max.toDouble(),
                                step.toDouble(),
                                allow,
                                SliderMode.Steps,
                            )
                    }
                SettingsNumbers.SliderMapping(bounds)
            } catch (failure: IllegalArgumentException) {
                processorError(
                    "Invalid slider steps on ${property.simpleName.asString()}: ${failure.message}",
                )
            }
        }
        return CodeBlock.of(
            "%T.finite%N(%T.Type.%N, %L, %L, %L, %L, %T.%N)",
            number,
            valueKind,
            rangeInfo,
            type,
            "$min$suffix",
            "$max$suffix",
            "$step$suffix",
            allow,
            ClassName(CORE_PACKAGE, "SliderMode"),
            sliderMode,
        )
    }

    private fun KSPropertyDeclaration.finiteAnnotations(): List<KSAnnotation> =
        annotations
            .filter {
                it.shortName.asString() in
                    setOf("FiniteNumber", "FiniteInt", "FiniteFloat", "FiniteLong", "FiniteDouble")
            }
            .toList()

    private fun KSDeclaration.annotation(name: String): KSAnnotation? = annotations.firstOrNull {
        it.shortName.asString() == name
    }

    private fun KSType.qualifiedName(): String? = declaration.qualifiedName?.asString()

    private fun KSType.isSupportedNumber(): Boolean =
        qualifiedName() in
            setOf(
                "kotlin.Int",
                "kotlin.Long",
                "kotlin.Float",
                "kotlin.Double",
            )

    private fun KSClassDeclaration.isChoice(): Boolean =
        classKind == ClassKind.ENUM_CLASS || Modifier.SEALED in modifiers

    private fun KSClassDeclaration.hasCompanionObject(): Boolean =
        declarations.filterIsInstance<KSClassDeclaration>().any { it.isCompanionObject }

    private fun KSClassDeclaration.implementsResources(): Boolean = superTypes.any {
        val parent = it.resolve().declaration as? KSClassDeclaration
        parent?.qualifiedName?.asString() == "$CORE_PACKAGE.SettingsResources" ||
            parent?.implementsResources() == true
    }

    private fun KSClassDeclaration.providesResources(): Boolean =
        (classKind == ClassKind.OBJECT && implementsResources()) ||
            declarations.filterIsInstance<KSClassDeclaration>().any {
                it.isCompanionObject && it.implementsResources()
            }

    private fun Any?.enumName(): String? =
        when (this) {
            is KSClassDeclaration -> simpleName.asString()
            is KSType -> declaration.simpleName.asString()
            else -> null
        }

    private fun read(path: List<String>, root: String = "store.value"): String =
        readCode(path, CodeBlock.of("%L", root)).toString()

    private fun readCode(
        path: List<String>,
        root: CodeBlock = CodeBlock.of("store.value"),
    ): CodeBlock = path.fold(root) { receiver, name -> CodeBlock.of("%L.%N", receiver, name) }

    private fun copyCode(
        path: List<String>,
        value: CodeBlock,
        root: CodeBlock = CodeBlock.of("current"),
    ): CodeBlock {
        val name = path.first()
        val nested =
            if (path.size == 1) value
            else copyCode(path.drop(1), value, CodeBlock.of("%L.%N", root, name))
        return CodeBlock.of("%L.copy(%N = %L)", root, name, nested)
    }

    private fun String.titlecaseFirst(): String = replaceFirstChar {
        if (it.isLowerCase()) it.titlecase() else it.toString()
    }

