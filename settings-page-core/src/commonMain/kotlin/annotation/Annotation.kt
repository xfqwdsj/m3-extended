/**
 * Marks a class or enum entry as a settings value holder for [Selector] or [MultiSelector] settings
 * items.
 *
 * The class must be a subclass of a `sealed class` or `sealed interface`, or an entry of an `enum
 * class`. Each subclass or enum entry represents an option in the selector.
 *
 * @param resourceClass a [KClass] of an `object` or `companion object` that contains string
 *   resources for the options. Consider using [SettingsResources] to generate the resource class.
 *   If the type itself is a `object` or has a `companion object` that contains the resources, or
 *   the enum class implements [SettingsResources], leave this as `Unit::class` to use those
 *   resources.
 */
@Target(CLASS, PROPERTY, FIELD)
@Retention(SOURCE)
public annotation class SettingsValue(val resourceClass: KClass<*> = Unit::class)
