/**
 * Marks a class as a settings store.
 *
 * A [SettingsStoreDescriber] is generated by default. With [bindDataStore] disabled, the descriptor
 * accepts a storage-independent model and exposes the settings tree without persistence binding.
 *
 * With [SettingsResetMode.Menu], generated items read their reset values from a fresh no-argument
 * instance of the model. Every primary-constructor parameter must have a default value and the
 * constructor must be accessible to generated code. Use [SettingsResetMode.None] when the model
 * requires constructor arguments or should not expose reset values.
 */
@Target(CLASS)
@Retention(SOURCE)
public annotation class SettingsStore(
    val resetMode: SettingsResetMode = SettingsResetMode.None,
    /**
     * Generates a DataStore-bound descriptor; false accepts the independent SettingsModel contract.
     */
    val bindDataStore: Boolean = true,
)

/**
 * Marks a field as a settings item.
 *
 * The property must be declared in a data class's primary constructor and be readable by the
 * generated describer. The data class's `copy` function must also be accessible. This applies to
 * category properties and settings inside sealed options as well. Both `val` and `var` are
 * supported; body properties and computed properties cannot be edited by the generated binding.
 *
 * @param resourceObject a [KClass] of an `object` or `companion object` that implements
 *   [SettingsResources]. If the type of the field has a `companion object` that contains the
 *   resources, you can set this parameter to `Unit::class` to use that `companion object`.
 * @param type the type of the settings item. If set to [SettingsItemType.Auto], the type will be
 *   determined automatically based on the field's type. See [SettingsItemType] for supported field
 *   types.
 * @param dependsOn the names of sibling `Boolean` properties that gate this item. The generated
 *   item reacts while none or some of the named properties are not `true`, as determined by
 *   [dependencyType].
 * @param dependencyType how the item reacts when [dependsOn] is not satisfied.
 */
@Target(PROPERTY, FIELD)
@Retention(SOURCE)
public annotation class SettingsItem(
    val resourceObject: KClass<*> = Unit::class,
    val type: SettingsItemType = Auto,
    val dependsOn: Array<String> = [],
    val dependencyType: SettingsDependencyType = SettingsDependencyType.EnableDisable,
)

/** How a settings item reacts when its `dependsOn` is not satisfied. */
public enum class SettingsDependencyType {
    /** Keeps the item visible but not interactive. */
    EnableDisable,

    /** Hides the item. */
    ShowHide,
}

/**
 * Marks a field as a custom settings item.
 *
 * The field must also be annotated with [SettingsItem]. The Material page passes this identifier to
 * the caller's custom editor, which edits a draft.
 */
@Target(PROPERTY, FIELD)
@Retention(SOURCE)
public annotation class CustomSettingsItem(val rendererId: String)

/** Constraints and layout for a text setting. */
@Target(PROPERTY, FIELD)
@Retention(SOURCE)
public annotation class TextInput(
    val minLength: Int = 0,
    val maxLength: Int = Int.MAX_VALUE,
    val multiline: Boolean = false,
)

/** Defines the type of the settings item. */
public enum class SettingsItemType {
    /**
     * Automatically determine the type based on the field's type.
     *
     * Supported field types:
     * - `Boolean` -> [Switch]
     * - `enum class` `sealed class` `sealed interface` -> [Selector]
     * - `Set<enum class>` `Set<sealed class>` `Set<sealed interface>` -> [MultiSelector]
     * - `Int`, `Long`, `Float`, `Double` -> [SingleNumber]
     * - `Pair` of matching supported numbers -> [NumberRange]
     * - `String` -> [Text]
     * - If the field is annotated with [CustomSettingsItem], use this [Auto] type.
     */
    Auto,

    /** The category type. */
    Category,
}

/**
 * Marks a field as a finite number type for [SingleNumber] or [NumberRange] settings items.
 *
 * The field must be annotated with [SettingsItem].
 *
 * If you use this annotation twice on the same field, it will be treated as the type of the start
 * and end values of a [NumberRange] item based on the order of the annotations.
 *
 * @param describer a [KClass] of an `object` or `companion object` that implements
 *   [RangeBasedNumberInfo] for the specific number type. You can also use the specific annotations
 *   like [FiniteInt], [FiniteFloat], [FiniteLong], or [FiniteDouble] instead of this generic
 *   annotation.
 */
@Repeatable
@Target(PROPERTY, FIELD)
@Retention(SOURCE)
public annotation class FiniteNumber<T : Number>(val describer: KClass<out RangeBasedNumberInfo<T>>)

/**
 * Marks a field as a finite `Int` type for [SingleNumber] or [NumberRange] settings items.
 *
 * The field must be annotated with [SettingsItem].
 *
 * If you use this annotation twice on the same field, it will be treated as the type of the start
 * and end values of a [NumberRange] item based on the order of the annotations.
 *
 * @param type the type of number input control to use. See [RangeBasedNumberInfo.Type] for details.
 * @param min the minimum value (inclusive).
 * @param max the maximum value (inclusive).
 * @param step the step value for increment/decrement controls.
 * @param allowInput whether to allow direct text input.
 */
@Repeatable
@Target(PROPERTY, FIELD)
@Retention(SOURCE)
public annotation class FiniteInt(
    val type: RangeBasedNumberInfo.Type,
    val min: Int,
    val max: Int,
    val step: Int = 1,
    val allowInput: Boolean = true,
    val sliderMode: SliderMode = SliderMode.Continuous,
)

