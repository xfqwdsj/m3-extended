package top.ltfan.m3x.datastore.processor.generator

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeName
import com.squareup.kotlinpoet.TypeSpec

/**
 * Generates `<Model>Store.kt`: the `StoreDefinition` object, one delegate per constructor parameter
 * and the `@Derived` delegates.
 */
class StoreFileGenerator {
    fun generate(model: StoreModel): FileSpec {
        val className = model.className
        val definitionName = "${className.simpleName}Store"
        val file =
            FileSpec.builder(className.packageName, definitionName)
                .addFileComment("Auto generated by datastore-processor. Do not modify!")

        file.addType(definition(model, definitionName))

        val receiver = MUTABLE_STATE_STORE.parameterizedBy(className)
        model.properties.forEach { property -> file.addProperty(delegate(property, receiver)) }
        model.derivations.forEach { derived ->
            file.addProperty(derivedProperty(derived, receiver))
        }

        return file.build()
    }

    private fun definition(model: StoreModel, definitionName: String): TypeSpec {
        val className = model.className
        return TypeSpec.objectBuilder(definitionName)
            .addSuperinterface(STORE_DEFINITION.parameterizedBy(className))
            .addProperty(
                PropertySpec.builder("name", STRING, KModifier.OVERRIDE)
                    .initializer("%S", model.storeName)
                    .build(),
            )
            .addProperty(
                PropertySpec.builder("defaultValue", className, KModifier.OVERRIDE)
                    .initializer("%T()", className)
                    .build(),
            )
            .addProperty(
                PropertySpec.builder(
                        "codec",
                        STORE_CODEC.parameterizedBy(className),
                        KModifier.OVERRIDE,
                    )
                    .initializer(
                        "%T.%N(%T.serializer())",
                        model.codec,
                        model.codecFunction,
                        className,
                    )
                    .build(),
            )
            .build()
    }

    private fun delegate(property: PropertyModel, receiver: TypeName): PropertySpec =
        PropertySpec.builder(
                property.name,
                READ_WRITE_PROPERTY.parameterizedBy(ANY.copy(nullable = true), property.type),
            )
            .receiver(receiver)
            .getter(
                FunSpec.getterBuilder()
                    .addStatement(
                        "return property(get = { it.%N }, set = { settings, value -> settings.copy(%N = value) })",
                        property.name,
                        property.name,
                    )
                    .build(),
            )
            .build()

    private fun derivedProperty(derived: DerivedModel, receiver: TypeName): PropertySpec {
        val read = derivedRead(derived)
        val getter = FunSpec.getterBuilder().addStatement("return %L", read).build()
        val builder =
            PropertySpec.builder(derived.name, derived.type, KModifier.PUBLIC)
                .receiver(receiver)
                .getter(getter)

        val function = derived.function ?: return builder.build()

        return builder
            .mutable(true)
            .setter(
                FunSpec.setterBuilder()
                    .addParameter("v", derived.type)
                    .addStatement("%L", derivedWrite(derived, function))
                    .build(),
            )
            .build()
    }

    private fun derivedRead(derived: DerivedModel): CodeBlock {
        val access = CodeBlock.of("value.%N", derived.getter)
        return derived.owner?.let { owner -> CodeBlock.of("with(%T) { %L }", owner, access) }
            ?: access
    }

    private fun derivedWrite(derived: DerivedModel, function: String): CodeBlock {
        val access = CodeBlock.of("current.%N(v)", function)
        val invoke =
            derived.owner?.let { owner -> CodeBlock.of("with(%T) { %L }", owner, access) } ?: access
        return CodeBlock.of("update { current -> %L }", invoke)
    }

    private companion object {
        val ANY = ClassName("kotlin", "Any")
        val STRING = ClassName("kotlin", "String")
        val READ_WRITE_PROPERTY = ClassName("kotlin.properties", "ReadWriteProperty")
        val STORE_DEFINITION = ClassName("top.ltfan.m3x.datastore", "StoreDefinition")
        val STORE_CODEC = ClassName("top.ltfan.m3x.datastore", "StoreCodec")
        val MUTABLE_STATE_STORE = ClassName("top.ltfan.m3x.datastore", "MutableStore")
    }
}
